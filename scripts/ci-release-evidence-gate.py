#!/usr/bin/env python3
"""Fail-closed CI bridge for signed release and external evidence bundles.

The bundles are supplied by a protected GitHub environment, not generated by
this workflow.  This script decodes them in memory, binds the release manifest
to the exact workflow commit, and invokes both asymmetric evidence validators.
It never prints the supplied documents or private configuration.
"""
from __future__ import annotations

import base64
import json
import os
from pathlib import Path
import re
import sys
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools/runtime"))

from elmpay_runtime.common import GateReport, ValidationError, read_json  # noqa: E402
from elmpay_runtime.external_evidence import validate_external_evidence  # noqa: E402
from elmpay_runtime.release import release_binding, verify_release  # noqa: E402


INPUTS = {
    "ELMPAY_RELEASE_MANIFEST_B64": "release manifest",
    "ELMPAY_RELEASE_TRUST_B64": "release trust",
    "ELMPAY_EXTERNAL_EVIDENCE_B64": "external evidence bundle",
    "ELMPAY_EXTERNAL_TRUST_B64": "external evidence trust",
}
MAX_ENCODED_BYTES = 1_000_000
COMMIT = re.compile(r"^[0-9a-f]{40}$|^[0-9a-f]{64}$")


def _decode(name: str) -> dict[str, Any]:
    encoded = os.environ.get(name)
    if encoded is None or not encoded:
        raise ValidationError(f"protected CI input is missing: {name}")
    if len(encoded.encode("ascii", errors="ignore")) > MAX_ENCODED_BYTES:
        raise ValidationError(f"protected CI input is too large: {name}")
    try:
        raw = base64.b64decode(encoded, validate=True)
    except (ValueError, TypeError) as exc:
        raise ValidationError(f"protected CI input is not canonical base64: {name}") from exc
    if base64.b64encode(raw).decode("ascii") != encoded:
        raise ValidationError(f"protected CI input is not canonical base64: {name}")

    def reject_duplicates(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        value: dict[str, Any] = {}
        for key, item in pairs:
            if key in value:
                raise ValidationError(f"duplicate key in protected CI input: {name}:{key}")
            value[key] = item
        return value

    try:
        document = json.loads(
            raw.decode("utf-8"),
            object_pairs_hook=reject_duplicates,
            parse_constant=lambda value: (_ for _ in ()).throw(
                ValidationError(f"non-finite number in protected CI input: {name}:{value}")
            ),
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValidationError(f"protected CI input is not valid UTF-8 JSON: {name}") from exc
    if not isinstance(document, dict):
        raise ValidationError(f"protected CI input must be an object: {name}")
    return document


def _context() -> str:
    expected = {
        "GITHUB_ACTIONS": "true",
        "ELMPAY_GATE_EVENT_NAME": "push",
        "ELMPAY_GATE_REPOSITORY": "zpcaiai/elmpay",
        "ELMPAY_GATE_REF": "refs/heads/main",
    }
    for name, value in expected.items():
        if os.environ.get(name) != value:
            raise ValidationError(f"untrusted release-gate context: {name}")
    commit = os.environ.get("ELMPAY_GATE_SHA", "")
    if not COMMIT.fullmatch(commit):
        raise ValidationError("release-gate commit SHA is missing or invalid")
    return commit


def main() -> int:
    try:
        expected_commit = _context()
        documents = {name: _decode(name) for name in INPUTS}
        manifest = documents["ELMPAY_RELEASE_MANIFEST_B64"]
        if manifest.get("commitSha") != expected_commit:
            raise ValidationError("signed release manifest is not bound to the workflow commit")
        release_report = verify_release(
            manifest,
            read_json(ROOT / "platform/compliance/required-release-gates.json"),
            documents["ELMPAY_RELEASE_TRUST_B64"],
        )
        external_report = validate_external_evidence(
            read_json(ROOT / "platform/compliance/external-evidence-policy.json"),
            documents["ELMPAY_EXTERNAL_EVIDENCE_B64"],
            documents["ELMPAY_EXTERNAL_TRUST_B64"],
            expected_binding=release_binding(manifest),
        )
        reasons = [
            *(f"release:{reason}" for reason in release_report.reasons),
            *(f"external_evidence:{reason}" for reason in external_report.reasons),
        ]
        report = GateReport.from_reasons(
            reasons, [*release_report.checks, *external_report.checks]
        )
    except (KeyError, TypeError, ValueError, ValidationError) as exc:
        report = GateReport.from_reasons([f"release_evidence_gate_invalid:{exc}"])
    print(json.dumps({
        "allowed": report.allowed,
        "reasons": list(report.reasons),
        "checks": list(report.checks),
        "certificationStatus": "EXTERNAL_EVIDENCE_VERIFIED" if report.allowed else "NOT_CERTIFIED",
    }, sort_keys=True, separators=(",", ":")))
    return 0 if report.allowed else 2


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Emit the full trace graph as machine-readable runtime evidence.

The human-readable matrix lives in ``docs/traceability/MATRIX.md`` and is
regenerated by ``scripts/render-docs.py``. This script emits the same graph as
JSON, plus the reverse-coverage summary that makes gaps countable, and exits
non-zero when anything is uncovered.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tools.paygov.catalogue import module_names  # noqa: E402
from tools.paygov.traceability import build_graph  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    graph = build_graph(ROOT)
    requirements = graph["requirements"]
    claimed_controls: dict[str, list[str]] = {}
    owners: dict[str, list[str]] = {}
    batches: dict[str, list[str]] = {}
    for req in requirements:
        for control in req["controls"]:
            claimed_controls.setdefault(control, []).append(req["id"])
        owners.setdefault(req["owner_module"], []).append(req["id"])
        for batch in req["verified_by_batches"]:
            batches.setdefault(batch, []).append(req["id"])

    universe = graph["rules"] + graph["controls"]
    uncovered_controls = [c for c in universe if c not in claimed_controls]
    uncovered_modules = sorted(module_names(str(ROOT)) - set(owners))
    unclaimed_requirements = [r["id"] for r in requirements
                              if r["id"] not in graph["capability_of"]]

    report = {
        "requirements_total": len(requirements),
        "capabilities_total": len(set(graph["capability_of"].values())),
        "adrs_total": len(graph["adrs"]),
        "non_negotiables_total": len(graph["rules"]),
        "controls_total": len(graph["controls"]),
        "batches_with_evidence": sorted(graph["batch_evidence"]),
        "requirements_per_control": {k: sorted(v) for k, v in sorted(claimed_controls.items())},
        "requirements_per_module": {k: sorted(v) for k, v in sorted(owners.items())},
        "requirements_per_batch": {k: sorted(v) for k, v in sorted(batches.items())},
        "uncovered_controls": uncovered_controls,
        "uncovered_modules": uncovered_modules,
        "unclaimed_requirements": unclaimed_requirements,
    }
    out = ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
                   encoding="utf-8")
    print(json.dumps({k: v for k, v in report.items() if not isinstance(v, dict)},
                     ensure_ascii=False, indent=2))
    return 1 if uncovered_controls or uncovered_modules or unclaimed_requirements else 0


if __name__ == "__main__":
    raise SystemExit(main())

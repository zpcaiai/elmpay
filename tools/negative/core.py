def _reshard(commands: list, shards: list[str]) -> list:
    """Replace every sharded invocation with exactly the given shard labels."""
    kept = [c for c in commands if "--shard" not in c.get("command", "")]
    return kept + [{"purpose": "runtime fail-closed proof", "expect": 0,
                    "command": f"python3 scripts/negative-controls.py --shard {label}",
                    "save_to": f"runtime/negative-controls-{label.replace('/', '-')}.log"}
                   for label in shards]


